//! Immutable per-file and whole-project adapter requests.
//!
//! Checked snapshots bind concrete VFS bytes to full-file repository generation
//! references before any adapter can observe individual or aggregate inputs.

use std::{
    collections::{BTreeMap, BTreeSet},
    fmt,
    sync::Arc,
};

use rootlight_ids::{ContentHash, content_hash};
use rootlight_ir::{AnalysisTier, BuildContextIdentity, SourceRef, SourceSpan};
use rootlight_vfs::{RelativePath, SourceSnapshot};

use crate::{
    descriptor::{EncodingId, LanguageId, validated_label},
    error::{LabelError, LabelField, LabelViolation, RequestError, ResourceKind, SnapshotError},
    limits::AnalysisLimits,
};

const MAX_PROJECT_ID_BYTES: usize = 1_024;
const MAX_TRANSFORMATION_ID_BYTES: usize = 128;
const GENERATED_ORIGIN_RULE_VERSION: &str = "rootlight.generated-origin.v1";

/// Canonical identity for one project analysis unit.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct AnalysisUnitId(String);

impl AnalysisUnitId {
    /// Creates a bounded source-free analysis-unit identity.
    ///
    /// # Errors
    ///
    /// Returns [`LabelError`] when the identity is empty, oversized, or
    /// contains bytes outside the canonical label grammar.
    pub fn new(value: &str) -> Result<Self, LabelError> {
        validated_project_label(LabelField::AnalysisUnit, value, MAX_PROJECT_ID_BYTES).map(Self)
    }

    /// Returns the canonical identity text.
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

