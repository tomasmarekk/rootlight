/// One project-relative mapping from generated bytes to their origin.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedOriginMapping {
    generated: SourceSpan,
    origin_path: RelativePath,
    origin: SourceSpan,
    transformation: TransformationId,
    generator_digest: Option<ContentHash>,
}

impl GeneratedOriginMapping {
    /// Creates a mapping whose source ownership and ranges are request-validated.
    #[must_use]
    pub fn new(
        generated: SourceSpan,
        origin_path: RelativePath,
        origin: SourceSpan,
        transformation: TransformationId,
        generator_digest: Option<ContentHash>,
    ) -> Self {
        Self {
            generated,
            origin_path,
            origin,
            transformation,
            generator_digest,
        }
    }

    /// Returns the mapped generated-source span.
    #[must_use]
    pub const fn generated(&self) -> SourceSpan {
        self.generated
    }

    /// Returns the canonical repository-relative origin path.
    #[must_use]
    pub const fn origin_path(&self) -> &RelativePath {
        &self.origin_path
    }

    /// Returns the origin byte span.
    #[must_use]
    pub const fn origin(&self) -> SourceSpan {
        self.origin
    }

    /// Returns the transformation identity.
    #[must_use]
    pub const fn transformation(&self) -> &TransformationId {
        &self.transformation
    }

    /// Returns the optional generator binary or configuration digest.
    #[must_use]
    pub const fn generator_digest(&self) -> Option<ContentHash> {
        self.generator_digest
    }

    /// Returns the canonical provenance rule for the mapping transformation.
    ///
    /// The normalized source-mapping record has no transformation fields of
    /// its own, so adapters retain this bounded identity in its referenced
    /// provenance record instead of dropping generator evidence.
    #[must_use]
    pub fn provenance_rule(&self) -> String {
        match self.generator_digest {
            Some(digest) => format!(
                "{GENERATED_ORIGIN_RULE_VERSION}:{}:{digest}",
                self.transformation.as_str()
            ),
            None => format!(
                "{GENERATED_ORIGIN_RULE_VERSION}:{}:none",
                self.transformation.as_str()
            ),
        }
    }

    fn accounted_bytes(&self) -> Result<usize, RequestError> {
        self.origin_path
            .identity_bytes()
            .len()
            .checked_add(self.transformation.as_str().len())
            .and_then(|bytes| bytes.checked_add(4 * size_of::<u64>()))
            .and_then(|bytes| {
                bytes.checked_add(
                    self.generator_digest
                        .map_or(0, |digest| digest.as_bytes().len()),
                )
            })
            .ok_or(RequestError::ProjectAccountingOverflow)
    }
}

/// One immutable generation-bound input to a project analyzer.
#[derive(Debug, Clone)]
pub struct ProjectSourceInput<'a> {
    source: GenerationBoundSnapshot<'a>,
    language: LanguageId,
    encoding: EncodingId,
    generated: bool,
    origins: Arc<Vec<GeneratedOriginMapping>>,
}

impl<'a> ProjectSourceInput<'a> {
    /// Creates a project source input; aggregate request construction validates it.
    #[must_use]
    pub fn new(
        source: GenerationBoundSnapshot<'a>,
        language: LanguageId,
        encoding: EncodingId,
        generated: bool,
        origins: Vec<GeneratedOriginMapping>,
    ) -> Self {
        Self {
            source,
            language,
            encoding,
            generated,
            origins: Arc::new(origins),
        }
    }

    /// Returns the immutable generation-bound source.
    #[must_use]
    pub const fn source(&self) -> &GenerationBoundSnapshot<'a> {
        &self.source
    }

    /// Returns the source language identity.
    #[must_use]
    pub const fn language(&self) -> &LanguageId {
        &self.language
    }

    /// Returns the declared source encoding.
    #[must_use]
    pub const fn encoding(&self) -> &EncodingId {
        &self.encoding
    }

    /// Reports whether the repository classified this source as generated.
    #[must_use]
    pub const fn is_generated(&self) -> bool {
        self.generated
    }

    /// Returns sorted, disjoint project-relative generated-origin mappings.
    #[must_use]
    pub fn origins(&self) -> &[GeneratedOriginMapping] {
        self.origins.as_slice()
    }
}

/// One bounded transactional request over a complete project analysis unit.
#[derive(Debug, Clone)]
pub struct ProjectAnalysisRequest<'a> {
    analysis_unit: AnalysisUnitId,
    build_target: BuildTargetId,
    build_context: BuildContextIdentity,
    configuration_digest: ContentHash,
    context_manifest: &'a [u8],
    inputs: Arc<Vec<ProjectSourceInput<'a>>>,
    anchor: SourceRef,
    requested_tier: AnalysisTier,
    total_source_bytes: usize,
    limits: &'a AnalysisLimits,
}

impl<'a> ProjectAnalysisRequest<'a> {
    /// Creates a canonical multi-file project request.
    ///
    /// Inputs must be strictly sorted by [`RelativePath::identity_bytes`] and
    /// belong to one repository generation. Source identity, all mapping
    /// ranges, and aggregate project quotas are validated before an analyzer
    /// can observe the request.
    ///
    /// # Errors
    ///
    /// Returns [`RequestError`] for disabled project admission, empty or
    /// noncanonical inputs, inconsistent generation identity, invalid
    /// generated-origin mappings, accounting overflow, or any exceeded
    /// per-file or aggregate limit.
    #[allow(clippy::too_many_arguments)]
    pub fn new(
        analysis_unit: AnalysisUnitId,
        build_target: BuildTargetId,
        build_context: BuildContextIdentity,
        configuration_digest: ContentHash,
        context_manifest: &'a [u8],
        inputs: Vec<ProjectSourceInput<'a>>,
        requested_tier: AnalysisTier,
        limits: &'a AnalysisLimits,
    ) -> Result<Self, RequestError> {
        let project_limits = limits
            .project()
            .ok_or(RequestError::ProjectAnalysisDisabled)?;
        let anchor = inputs
            .first()
            .ok_or(RequestError::EmptyProject)?
            .source()
            .source_ref()
            .clone();
        require_project_limit(
            ResourceKind::ProjectFiles,
            inputs.len(),
            project_limits.max_files(),
        )?;
        require_project_limit(
            ResourceKind::ProjectContextBytes,
            context_manifest.len(),
            project_limits.max_context_bytes(),
        )?;
        if content_hash(context_manifest) != configuration_digest {
            return Err(RequestError::ProjectConfigurationDigestMismatch);
        }
        require_project_limit(
            ResourceKind::AnalysisUnitBytes,
            analysis_unit.as_str().len(),
            project_limits.max_analysis_unit_bytes(),
        )?;
        require_project_limit(
            ResourceKind::BuildTargetBytes,
            build_target.as_str().len(),
            project_limits.max_build_target_bytes(),
        )?;

        let mut total_source_bytes = 0_usize;
        let mut total_mappings = 0_usize;
        let mut total_mapping_bytes = 0_usize;
        let mut previous_path: Option<&[u8]> = None;
        let mut files = BTreeSet::new();
        let mut paths = BTreeMap::new();
        for (index, input) in inputs.iter().enumerate() {
            let source = input.source().source_ref();
            if source.repository() != anchor.repository() {
                return Err(RequestError::ProjectRepositoryMismatch { index });
            }
            if source.generation() != anchor.generation() {
                return Err(RequestError::ProjectGenerationMismatch { index });
            }
            if !files.insert(source.span().file()) {
                return Err(RequestError::DuplicateProjectFile { index });
            }
            let path = input.source().path().identity_bytes();
            if previous_path.is_some_and(|previous| previous >= path) {
                return Err(RequestError::ProjectPathOrder { index });
            }
            previous_path = Some(path);
            paths.insert(path, index);
            validate_source_size(input.source(), limits)?;
            total_source_bytes = total_source_bytes
                .checked_add(input.source().bytes().len())
                .ok_or(RequestError::ProjectAccountingOverflow)?;
            if !input.generated && !input.origins.is_empty() {
                return Err(RequestError::OriginsRequireGeneratedSource { index });
            }
            total_mappings = total_mappings
                .checked_add(input.origins.len())
                .ok_or(RequestError::ProjectAccountingOverflow)?;
            for mapping in input.origins.iter() {
                total_mapping_bytes = total_mapping_bytes
                    .checked_add(mapping.accounted_bytes()?)
                    .ok_or(RequestError::ProjectAccountingOverflow)?;
            }
        }

        require_project_limit(
            ResourceKind::ProjectSourceBytes,
            total_source_bytes,
            project_limits.max_total_source_bytes(),
        )?;
        require_project_limit(
            ResourceKind::GeneratedMappings,
            total_mappings,
            project_limits.max_generated_mappings(),
        )?;
        require_project_limit(
            ResourceKind::GeneratedMappingBytes,
            total_mapping_bytes,
            project_limits.max_generated_mapping_bytes(),
        )?;
        validate_project_mappings(&inputs, &paths)?;

        Ok(Self {
            analysis_unit,
            build_target,
            build_context,
            configuration_digest,
            context_manifest,
            inputs: Arc::new(inputs),
            anchor,
            requested_tier,
            total_source_bytes,
            limits,
        })
    }

    /// Returns the canonical analysis-unit identity.
    #[must_use]
    pub const fn analysis_unit(&self) -> &AnalysisUnitId {
        &self.analysis_unit
    }

    /// Returns the selected canonical build target.
    #[must_use]
    pub const fn build_target(&self) -> &BuildTargetId {
        &self.build_target
    }

    /// Returns the exact build-context identity.
    #[must_use]
    pub const fn build_context(&self) -> BuildContextIdentity {
        self.build_context
    }

    /// Returns the canonical project configuration digest.
    #[must_use]
    pub const fn configuration_digest(&self) -> ContentHash {
        self.configuration_digest
    }

    /// Returns the bounded canonical build-context manifest.
    #[must_use]
    pub const fn context_manifest(&self) -> &[u8] {
        self.context_manifest
    }

    /// Returns canonically ordered generation-bound source inputs.
    #[must_use]
    pub fn inputs(&self) -> &[ProjectSourceInput<'a>] {
        self.inputs.as_slice()
    }

    /// Returns the highest analysis tier requested by the caller.
    #[must_use]
    pub const fn requested_tier(&self) -> AnalysisTier {
        self.requested_tier
    }

    /// Returns aggregate admitted source bytes.
    #[must_use]
    pub const fn total_source_bytes(&self) -> usize {
        self.total_source_bytes
    }

    /// Returns the repository-generation anchor shared by every input.
    #[must_use]
    pub(crate) const fn anchor(&self) -> &SourceRef {
        &self.anchor
    }

    /// Returns explicit per-file, aggregate, stream, and IR limits.
    #[must_use]
    pub const fn limits(&self) -> &AnalysisLimits {
        self.limits
    }
}

