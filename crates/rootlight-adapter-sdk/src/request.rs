/// Concrete immutable VFS bytes bound to one full-file generation reference.
#[derive(Clone)]
pub struct GenerationBoundSnapshot<'a> {
    snapshot: &'a SourceSnapshot,
    source: SourceRef,
}

impl<'a> GenerationBoundSnapshot<'a> {
    /// Binds a VFS snapshot to an exact full-file [`SourceRef`].
    ///
    /// # Errors
    ///
    /// Returns [`SnapshotError`] when file, hash, or full-file span identity
    /// differs from the captured bytes.
    pub fn new(snapshot: &'a SourceSnapshot, source: &SourceRef) -> Result<Self, SnapshotError> {
        if snapshot.file() != source.span().file() {
            return Err(SnapshotError::FileMismatch);
        }
        if snapshot.content_hash() != source.content_hash() {
            return Err(SnapshotError::ContentHashMismatch);
        }
        let byte_length =
            u64::try_from(snapshot.content().len()).map_err(|_| SnapshotError::LengthOverflow)?;
        if source.span().start_byte() != 0
            || source.span().end_byte() != byte_length
            || snapshot.metadata().length != byte_length
        {
            return Err(SnapshotError::NotFullFile);
        }
        Ok(Self {
            snapshot,
            source: source.clone(),
        })
    }

    /// Returns the immutable captured source bytes.
    #[must_use]
    pub fn bytes(&self) -> &[u8] {
        self.snapshot.content()
    }

    /// Returns the canonical repository-relative path.
    #[must_use]
    pub const fn path(&self) -> &RelativePath {
        self.snapshot.path()
    }

    /// Returns the exact full-file generation reference.
    #[must_use]
    pub const fn source_ref(&self) -> &SourceRef {
        &self.source
    }

    /// Returns the underlying immutable VFS snapshot.
    #[must_use]
    pub const fn snapshot(&self) -> &SourceSnapshot {
        self.snapshot
    }
}

impl fmt::Debug for GenerationBoundSnapshot<'_> {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("GenerationBoundSnapshot")
            .field("source", &self.source)
            .field("byte_length", &self.snapshot.content().len())
            .finish()
    }
}

/// One bounded synchronous parse request for immutable source bytes.
#[derive(Debug, Clone)]
pub struct ParseRequest<'a> {
    source: GenerationBoundSnapshot<'a>,
    language: LanguageId,
    encoding: EncodingId,
    included_ranges: Arc<Vec<IncludedRange>>,
    limits: &'a AnalysisLimits,
}

impl<'a> ParseRequest<'a> {
    /// Creates a checked per-file parse request.
    ///
    /// # Errors
    ///
    /// Returns [`RequestError`] when source bytes or included ranges violate
    /// the explicit analysis limits.
    pub fn new(
        source: GenerationBoundSnapshot<'a>,
        language: LanguageId,
        encoding: EncodingId,
        included_ranges: Vec<IncludedRange>,
        limits: &'a AnalysisLimits,
    ) -> Result<Self, RequestError> {
        validate_request_input(&source, &included_ranges, limits)?;
        Ok(Self {
            source,
            language,
            encoding,
            included_ranges: Arc::new(included_ranges),
            limits,
        })
    }

    /// Returns the immutable generation-bound source.
    #[must_use]
    pub const fn source(&self) -> &GenerationBoundSnapshot<'a> {
        &self.source
    }

    /// Returns the requested language identity.
    #[must_use]
    pub const fn language(&self) -> &LanguageId {
        &self.language
    }

    /// Returns the declared source encoding.
    #[must_use]
    pub const fn encoding(&self) -> &EncodingId {
        &self.encoding
    }

    /// Returns sorted, disjoint embedded source ranges.
    #[must_use]
    pub fn included_ranges(&self) -> &[IncludedRange] {
        self.included_ranges.as_slice()
    }

    /// Returns shared ownership of the checked included-range identities.
    ///
    /// Parser implementations can retain this immutable owner for incremental
    /// reuse metadata without cloning language labels embedded in each range.
    #[must_use]
    pub fn shared_included_ranges(&self) -> Arc<Vec<IncludedRange>> {
        Arc::clone(&self.included_ranges)
    }

    /// Returns explicit analysis limits.
    #[must_use]
    pub const fn limits(&self) -> &AnalysisLimits {
        self.limits
    }
}

/// One bounded synchronous normalized-IR analysis request.
#[derive(Debug, Clone)]
pub struct AnalysisRequest<'a> {
    source: GenerationBoundSnapshot<'a>,
    language: LanguageId,
    encoding: EncodingId,
    included_ranges: Arc<Vec<IncludedRange>>,
    generated: Option<bool>,
    tier: AnalysisTier,
    build_context: BuildContextIdentity,
    limits: &'a AnalysisLimits,
}

impl<'a> AnalysisRequest<'a> {
    /// Creates a checked per-file analysis request.
    ///
    /// # Errors
    ///
    /// This compatibility constructor selects UTF-8 and full-file analysis.
    /// Use [`Self::new_with_parse_context`] for embedded source ranges.
    ///
    /// Returns [`RequestError`] when the immutable source violates its explicit
    /// request bound.
    pub fn new(
        source: GenerationBoundSnapshot<'a>,
        language: LanguageId,
        tier: AnalysisTier,
        build_context: BuildContextIdentity,
        limits: &'a AnalysisLimits,
    ) -> Result<Self, RequestError> {
        Self::new_with_parse_context(
            source,
            language,
            EncodingId::utf8(),
            Vec::new(),
            tier,
            build_context,
            limits,
        )
    }

    /// Creates a checked analysis request with explicit parser input context.
    ///
    /// Carrying encoding and included ranges through the analyzer boundary lets
    /// parser-backed analyzers construct an equivalent [`ParseRequest`] without
    /// weakening or duplicating request validation.
    ///
    /// # Errors
    ///
    /// Returns [`RequestError`] when source bytes or included ranges violate
    /// the explicit analysis limits.
    #[allow(clippy::too_many_arguments)]
    pub fn new_with_parse_context(
        source: GenerationBoundSnapshot<'a>,
        language: LanguageId,
        encoding: EncodingId,
        included_ranges: Vec<IncludedRange>,
        tier: AnalysisTier,
        build_context: BuildContextIdentity,
        limits: &'a AnalysisLimits,
    ) -> Result<Self, RequestError> {
        validate_request_input(&source, &included_ranges, limits)?;
        Ok(Self {
            source,
            language,
            encoding,
            included_ranges: Arc::new(included_ranges),
            generated: None,
            tier,
            build_context,
            limits,
        })
    }

    /// Records whether the source was classified as generated.
    ///
    /// Compatibility constructors intentionally leave this classification
    /// unknown. Analyzers that require it must reject the request until a
    /// caller supplies the repository-owned classification through this
    /// builder.
    #[must_use]
    pub const fn with_generated_status(mut self, generated: bool) -> Self {
        self.generated = Some(generated);
        self
    }

    /// Returns the immutable generation-bound source.
    #[must_use]
    pub const fn source(&self) -> &GenerationBoundSnapshot<'a> {
        &self.source
    }

    /// Returns the requested language identity.
    #[must_use]
    pub const fn language(&self) -> &LanguageId {
        &self.language
    }

    /// Returns the declared source encoding.
    #[must_use]
    pub const fn encoding(&self) -> &EncodingId {
        &self.encoding
    }

    /// Returns sorted, disjoint embedded source ranges.
    #[must_use]
    pub fn included_ranges(&self) -> &[IncludedRange] {
        self.included_ranges.as_slice()
    }

    /// Creates the equivalent parser request with shared range ownership.
    ///
    /// The analysis request has already validated this parser input context,
    /// so the derived request preserves it without repeating validation or
    /// cloning language labels embedded in each included range.
    #[must_use]
    pub fn to_parse_request(&self) -> ParseRequest<'a> {
        ParseRequest {
            source: self.source.clone(),
            language: self.language.clone(),
            encoding: self.encoding.clone(),
            included_ranges: Arc::clone(&self.included_ranges),
            limits: self.limits,
        }
    }

    /// Returns the repository-owned generated-source classification, if known.
    #[must_use]
    pub const fn generated_status(&self) -> Option<bool> {
        self.generated
    }

    /// Returns the requested analysis tier.
    #[must_use]
    pub const fn tier(&self) -> AnalysisTier {
        self.tier
    }

    /// Returns the build-context identity.
    #[must_use]
    pub const fn build_context(&self) -> BuildContextIdentity {
        self.build_context
    }

    /// Returns explicit analysis limits.
    #[must_use]
    pub const fn limits(&self) -> &AnalysisLimits {
        self.limits
    }
}

fn validate_request_input(
    source: &GenerationBoundSnapshot<'_>,
    ranges: &[IncludedRange],
    limits: &AnalysisLimits,
) -> Result<(), RequestError> {
    validate_source_size(source, limits)?;
    validate_included_ranges(source, ranges, limits)
}

fn validate_source_size(
    source: &GenerationBoundSnapshot<'_>,
    limits: &AnalysisLimits,
) -> Result<(), RequestError> {
    let observed = source.bytes().len();
    if observed > limits.max_source_bytes() {
        Err(RequestError::SourceTooLarge {
            observed,
            limit: limits.max_source_bytes(),
        })
    } else {
        Ok(())
    }
}

fn validate_included_ranges(
    source: &GenerationBoundSnapshot<'_>,
    ranges: &[IncludedRange],
    limits: &AnalysisLimits,
) -> Result<(), RequestError> {
    if ranges.len() > limits.max_embedded_ranges() {
        return Err(RequestError::TooManyIncludedRanges {
            observed: ranges.len(),
            limit: limits.max_embedded_ranges(),
        });
    }
    let full = source.source_ref().span();
    let mut previous_end = full.start_byte();
    for (index, range) in ranges.iter().enumerate() {
        let span = range.span();
        if span.file() != full.file()
            || span.start_byte() < full.start_byte()
            || span.end_byte() > full.end_byte()
            || span.start_byte() == span.end_byte()
        {
            return Err(RequestError::IncludedRangeOutsideSource { index });
        }
        if span.start_byte() < previous_end {
            return Err(RequestError::IncludedRangeOrder { index });
        }
        previous_end = span.end_byte();
    }
    Ok(())
}

fn validate_project_mappings(
    inputs: &[ProjectSourceInput<'_>],
    paths: &BTreeMap<&[u8], usize>,
) -> Result<(), RequestError> {
    for (input_index, input) in inputs.iter().enumerate() {
        let full = input.source.source_ref().span();
        let mut previous_end = full.start_byte();
        for (mapping_index, mapping) in input.origins.iter().enumerate() {
            let generated = mapping.generated;
            if generated.file() != full.file()
                || generated.start_byte() < full.start_byte()
                || generated.end_byte() > full.end_byte()
                || generated.start_byte() == generated.end_byte()
            {
                return Err(RequestError::GeneratedOriginOutsideSource {
                    input: input_index,
                    mapping: mapping_index,
                });
            }
            if generated.start_byte() < previous_end {
                return Err(RequestError::GeneratedOriginOrder {
                    input: input_index,
                    mapping: mapping_index,
                });
            }
            previous_end = generated.end_byte();

            if mapping.origin.start_byte() == mapping.origin.end_byte() {
                return Err(RequestError::GeneratedOriginMismatch {
                    input: input_index,
                    mapping: mapping_index,
                });
            }
            let Some(origin_index) = paths.get(mapping.origin_path.identity_bytes()) else {
                return Err(RequestError::GeneratedOriginMismatch {
                    input: input_index,
                    mapping: mapping_index,
                });
            };
            let origin = inputs
                .get(*origin_index)
                .ok_or(RequestError::ProjectAccountingOverflow)?
                .source
                .source_ref()
                .span();
            if mapping.origin.file() != origin.file()
                || mapping.origin.start_byte() < origin.start_byte()
                || mapping.origin.end_byte() > origin.end_byte()
                || mapping.origin.start_byte() == mapping.origin.end_byte()
            {
                return Err(RequestError::GeneratedOriginMismatch {
                    input: input_index,
                    mapping: mapping_index,
                });
            }
        }
    }
    Ok(())
}

fn require_project_limit(
    resource: ResourceKind,
    observed: usize,
    limit: usize,
) -> Result<(), RequestError> {
    if observed > limit {
        Err(RequestError::ProjectLimit {
            resource,
            observed,
            limit,
        })
    } else {
        Ok(())
    }
}

fn validated_project_label(
    field: LabelField,
    value: &str,
    maximum_bytes: usize,
) -> Result<String, LabelError> {
    let violation = if value.is_empty() {
        Some(LabelViolation::Empty)
    } else if value.len() > maximum_bytes {
        Some(LabelViolation::TooLong)
    } else if !value.bytes().all(|byte| {
        byte.is_ascii_alphanumeric()
            || matches!(byte, b'_' | b'-' | b'.' | b'+' | b'#' | b'/' | b':' | b'@')
    }) {
        Some(LabelViolation::InvalidByte)
    } else {
        None
    };
    match violation {
        Some(violation) => Err(LabelError { field, violation }),
        None => Ok(value.to_owned()),
    }
}
