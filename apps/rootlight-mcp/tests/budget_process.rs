#[test]
#[ignore = "retained real-process evidence is generated by its dedicated CI gate"]
fn all_budget_tools_enforce_hard_limits_across_daemon_and_mcp_processes() {
    let fixture = fixture_root();
    let fixture_sha256 = fixture_digest(&fixture);
    let isolated = tempfile::tempdir().expect("isolated process fixture is available");
    let repository_root = isolated.path().join("repository");
    copy_regular_tree(&fixture, &repository_root);
    let state_dir = isolated.path().join("state");
    let runtime_dir = isolated.path().join("runtime");
    let mut daemon = DaemonProcess::spawn(&state_dir, &runtime_dir);
    daemon.wait_until_ready(&runtime_dir);
    let mut mcp = McpProcess::spawn(&state_dir, &runtime_dir);

    let first = index_repository(&mut mcp, &repository_root, "index-v1");
    fs::OpenOptions::new()
        .append(true)
        .open(repository_root.join("src").join("lib.rs"))
        .and_then(|mut file| {
            file.write_all(
                b"\npub fn budget_added(value: usize) -> usize {\n    value.saturating_sub(1)\n}\n",
            )
        })
        .expect("fixture v2 mutation is written");
    let second = index_repository(&mut mcp, &repository_root, "index-v2");
    assert_eq!(first.repository_id, second.repository_id);
    assert_ne!(first.generation_id, second.generation_id);

    let entry = locate(&mut mcp, &second, "budget_entry", "setup-entry");
    let helper = locate(&mut mcp, &second, "budget_helper", "setup-helper");
    let cases = tool_cases(&first, &second, &entry, &helper);
    assert_eq!(
        cases.iter().map(|case| case.tool).collect::<Vec<_>>(),
        EXPECTED_TOOLS
    );

    let tokenizer = tiktoken_rs::o200k_base().expect("pinned o200k tokenizer initializes");
    let mut observations = Vec::with_capacity(cases.len());
    for (index, case) in cases.into_iter().enumerate() {
        let baseline = mcp.call(
            &format!("baseline-{index}"),
            case.tool,
            case.arguments.clone(),
        );
        let baseline_measurement = measure_success(case.tool, &baseline, &tokenizer);

        let (limited_arguments, trigger, limit, expected_error) = limited_arguments(
            case.tool,
            case.arguments,
            baseline_measurement.serialized_json_bytes,
        );
        let limited = mcp.call(&format!("limited-{index}"), case.tool, limited_arguments);
        let limited_measurement = measure_error(case.tool, &limited, expected_error, &tokenizer);
        observations.push(ToolBudgetObservation {
            tool: case.tool,
            trigger,
            limit,
            baseline: baseline_measurement,
            limited: limited_measurement,
        });
    }

    mcp.finish();
    daemon.finish();

    let report = RuntimeBudgetReport {
        schema: REPORT_SCHEMA,
        source_revision: source_revision(),
        fixture: FixtureEvidence {
            name: "budget-runtime-repository-v1",
            sha256: fixture_sha256,
            regular_files: regular_files(&fixture).len(),
        },
        process_boundary: ProcessBoundary {
            daemon: "rootlight-daemon supervised stdio",
            mcp: "rootlight-mcp JSON-RPC stdio",
            indexed_generations: 2,
        },
        tokenizer: TokenizerEvidence {
            name: "o200k_base",
            implementation: "tiktoken-rs",
            implementation_version: "0.12.0",
        },
        cases: observations,
    };
    validate_report(&report);
    if let Some(path) = std::env::var_os(REPORT_ENV) {
        write_report(Path::new(&path), &report);
    }
}

