fn limited_arguments(
    tool: &str,
    mut arguments: Value,
    baseline_json_bytes: u64,
) -> (Value, &'static str, u64, &'static str) {
    if tool == "context.pack" {
        arguments["token_budget"] = json!(MIN_CONTEXT_TOKEN_LIMIT);
        return (
            arguments,
            "token_budget",
            MIN_CONTEXT_TOKEN_LIMIT,
            "BUDGET_EXCEEDED",
        );
    }
    if tool == "query.advanced" {
        arguments["cost_limit"] = json!(1);
        return (arguments, "cost_limit", 1, "COST_LIMIT");
    }
    let limit = baseline_json_bytes
        .saturating_sub(1)
        .max(MIN_RESPONSE_TOKEN_LIMIT);
    assert!(
        limit <= 16_000,
        "{tool} baseline exceeds the public max_tokens schema ceiling"
    );
    arguments
        .as_object_mut()
        .expect("tool arguments are objects")
        .insert("budget".to_owned(), json!({"max_tokens": limit}));
    (arguments, "budget.max_tokens", limit, "BUDGET_EXCEEDED")
}

fn measure_success(
    tool: &str,
    response: &Value,
    tokenizer: &tiktoken_rs::CoreBPE,
) -> SuccessMeasurement {
    assert_ne!(
        response["result"]["isError"], true,
        "{tool} baseline returned a public error: {response:#}"
    );
    let structured = &response["result"]["structuredContent"];
    assert!(
        structured.is_object(),
        "{tool} baseline omitted structured content"
    );
    let serialized = serde_json::to_vec(structured).expect("structured content serializes");
    let serialized_json_bytes =
        u64::try_from(serialized.len()).expect("serialized response length fits");
    let public_estimated_tokens = estimate_tokens(serialized.len());
    assert_eq!(
        structured["usage"]["json_bytes"].as_u64(),
        Some(serialized_json_bytes),
        "{tool} did not report authoritative serialized JSON bytes"
    );
    assert_eq!(
        structured["usage"]["estimated_tokens"].as_u64(),
        Some(public_estimated_tokens),
        "{tool} did not report the public deterministic estimate"
    );
    SuccessMeasurement {
        serialized_json_bytes,
        public_estimated_tokens,
        actual_o200k_tokens: actual_tokens(&serialized, tokenizer),
        structured_sha256: sha256_hex(&serialized),
    }
}

fn measure_error(
    tool: &str,
    response: &Value,
    expected_code: &'static str,
    tokenizer: &tiktoken_rs::CoreBPE,
) -> LimitMeasurement {
    assert_eq!(
        response["result"]["isError"], true,
        "{tool} hard limit did not return a checked public error: {response:#}"
    );
    let structured = &response["result"]["structuredContent"];
    assert_eq!(
        structured["error"]["code"], expected_code,
        "{tool} returned the wrong hard-limit error: {response:#}"
    );
    let serialized = serde_json::to_vec(structured).expect("structured error serializes");
    LimitMeasurement {
        error_code: expected_code,
        serialized_json_bytes: u64::try_from(serialized.len())
            .expect("serialized error length fits"),
        public_estimated_tokens: estimate_tokens(serialized.len()),
        actual_o200k_tokens: actual_tokens(&serialized, tokenizer),
        structured_sha256: sha256_hex(&serialized),
    }
}

fn actual_tokens(input: &[u8], tokenizer: &tiktoken_rs::CoreBPE) -> u64 {
    let text = std::str::from_utf8(input).expect("canonical JSON is UTF-8");
    u64::try_from(tokenizer.encode_with_special_tokens(text).len())
        .expect("token count fits unsigned evidence")
}

fn validate_report(report: &RuntimeBudgetReport) {
    assert!(valid_revision(&report.source_revision));
    assert_eq!(report.cases.len(), EXPECTED_TOOLS.len());
    assert_eq!(
        report
            .cases
            .iter()
            .map(|case| case.tool)
            .collect::<Vec<_>>(),
        EXPECTED_TOOLS
    );
    assert!(
        report.cases.iter().all(|case| {
            case.baseline.serialized_json_bytes > 0
                && case.baseline.public_estimated_tokens
                    == estimate_tokens(
                        usize::try_from(case.baseline.serialized_json_bytes)
                            .expect("response bytes fit usize"),
                    )
                && case.baseline.actual_o200k_tokens > 0
                && case.baseline.structured_sha256.len() == 64
                && case.limited.serialized_json_bytes > 0
                && case.limited.public_estimated_tokens
                    == estimate_tokens(
                        usize::try_from(case.limited.serialized_json_bytes)
                            .expect("error bytes fit usize"),
                    )
                && case.limited.actual_o200k_tokens > 0
                && case.limited.structured_sha256.len() == 64
        }),
        "every runtime case must retain measured byte and token evidence"
    );
}

fn write_report(path: &Path, report: &RuntimeBudgetReport) {
    let mut encoded = serde_json::to_vec_pretty(report).expect("runtime report serializes");
    encoded.push(b'\n');
    assert!(
        encoded.len() <= MAX_REPORT_BYTES,
        "runtime report exceeds its retained evidence ceiling"
    );
    if let Some(parent) = path
        .parent()
        .filter(|parent| !parent.as_os_str().is_empty())
    {
        fs::create_dir_all(parent).expect("runtime report directory is created");
    }
    fs::write(path, encoded).expect("runtime report is written");
}

fn source_revision() -> String {
    let revision = std::env::var(SOURCE_REVISION_ENV).unwrap_or_else(|_| {
        let output = Command::new("git")
            .args(["rev-parse", "HEAD"])
            .current_dir(Path::new(env!("CARGO_MANIFEST_DIR")).join("../.."))
            .output()
            .expect("git source revision command starts");
        assert!(
            output.status.success(),
            "git source revision command succeeds"
        );
        String::from_utf8(output.stdout)
            .expect("git source revision is UTF-8")
            .trim()
            .to_owned()
    });
    assert!(valid_revision(&revision), "source revision is canonical");
    revision
}

fn valid_revision(revision: &str) -> bool {
    matches!(revision.len(), 40 | 64)
        && revision
            .bytes()
            .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte))
}

fn fixture_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join("tests/fixtures/mcp/budget-runtime/repository")
}

fn regular_files(root: &Path) -> Vec<PathBuf> {
    fn walk(root: &Path, directory: &Path, output: &mut Vec<PathBuf>) {
        let mut entries = fs::read_dir(directory)
            .expect("fixture directory reads")
            .collect::<Result<Vec<_>, _>>()
            .expect("fixture entries read");
        entries.sort_by_key(std::fs::DirEntry::file_name);
        for entry in entries {
            let kind = entry.file_type().expect("fixture file type reads");
            assert!(!kind.is_symlink(), "fixture cannot contain symbolic links");
            if kind.is_dir() {
                walk(root, &entry.path(), output);
            } else if kind.is_file() {
                output.push(
                    entry
                        .path()
                        .strip_prefix(root)
                        .expect("fixture path stays below root")
                        .to_path_buf(),
                );
            }
        }
    }
    let mut output = Vec::new();
    walk(root, root, &mut output);
    output
}

fn fixture_digest(root: &Path) -> String {
    let mut digest = Sha256::new();
    for relative in regular_files(root) {
        let normalized = relative.to_string_lossy().replace('\\', "/");
        let bytes = fs::read(root.join(&relative)).expect("fixture file reads");
        digest.update(normalized.as_bytes());
        digest.update([0]);
        digest.update(
            u64::try_from(bytes.len())
                .expect("fixture length fits")
                .to_le_bytes(),
        );
        digest.update(&bytes);
    }
    sha256_hex(&digest.finalize())
}

fn copy_regular_tree(source: &Path, destination: &Path) {
    fs::create_dir_all(destination).expect("fixture destination is created");
    for relative in regular_files(source) {
        let target = destination.join(&relative);
        fs::create_dir_all(target.parent().expect("fixture file has a parent"))
            .expect("fixture parent directory is created");
        fs::copy(source.join(&relative), target).expect("fixture file is copied");
    }
}

fn sha256_hex(input: &[u8]) -> String {
    use std::fmt::Write as _;

    let digest = Sha256::digest(input);
    let mut encoded = String::with_capacity(64);
    for byte in digest {
        write!(encoded, "{byte:02x}").expect("writing to a string cannot fail");
    }
    encoded
}

fn index_repository(mcp: &mut McpProcess, root: &Path, id: &str) -> IndexReceipt {
    let response = mcp.call(
        id,
        "repo.index",
        json!({"root": root, "mode": "auto", "detached": false}),
    );
    assert_success(&response, "repo.index");
    let data = &response["result"]["structuredContent"]["data"];
    let repository_id = required_string(&data["repository_id"], "repository identity");
    let operation_id = required_string(&data["operation_id"], "operation identity");
    let generation_id = if data["state"] == "published" {
        required_string(&data["published_generation"], "published generation")
    } else {
        wait_for_publication(mcp, &operation_id)
    };
    IndexReceipt {
        repository_id,
        generation_id,
    }
}

fn wait_for_publication(mcp: &mut McpProcess, operation_id: &str) -> String {
    for attempt in 0..30 {
        let response = mcp.call(
            &format!("operation-{operation_id}-{attempt}"),
            "operation.status",
            json!({"operation_id": operation_id, "wait_ms": 1_000}),
        );
        assert_success(&response, "operation.status");
        let data = &response["result"]["structuredContent"]["data"];
        match data["operation"]["state"].as_str() {
            Some("published") => {
                return required_string(&data["published_generation"], "published generation");
            }
            Some("failed" | "cancelled") => {
                panic!("fixture indexing terminated without publication: {response:#}")
            }
            _ => {}
        }
    }
    panic!("fixture indexing did not publish within the bounded wait");
}

fn locate(mcp: &mut McpProcess, index: &IndexReceipt, query: &str, id: &str) -> LocatedSymbol {
    let response = mcp.call(
        id,
        "code.locate",
        json!({
            "repository": {"repository_id": index.repository_id},
            "generation": index.generation_id,
            "query": query,
            "search_modes": ["exact"],
            "max_results": 2
        }),
    );
    assert_success(&response, "code.locate");
    let matches = response["result"]["structuredContent"]["data"]["matches"]
        .as_array()
        .expect("code.locate returns matches");
    assert_eq!(matches.len(), 1, "setup locate returns one exact symbol");
    LocatedSymbol {
        symbol_id: required_string(&matches[0]["symbol_id"], "symbol identity"),
        source_ref: matches[0]["source_ref"].clone(),
    }
}

